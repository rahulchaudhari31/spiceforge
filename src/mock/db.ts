export const nextId = (items: { id: number }[]): number => {
  return items.reduce((max, item) => Math.max(max, item.id), 0) + 1;
};

export const makePaginator = <T>(items: T[], page: number = 1, perPage: number = 10) => {
  const total = items.length;
  const lastPage = Math.max(1, Math.ceil(total / perPage));
  const safePage = Math.min(Math.max(1, page), lastPage);
  const offset = (safePage - 1) * perPage;
  const slice = items.slice(offset, offset + perPage);
  return {
    current_page: safePage,
    data: slice,
    first_page_url: null,
    from: total === 0 ? 0 : offset + 1,
    last_page: lastPage,
    per_page: perPage,
    to: total === 0 ? 0 : offset + slice.length,
    total,
  };
};

export const matchesSearch = (values: unknown[], search?: string): boolean => {
  if (!search) return true;
  const needle = search.toLowerCase();
  return values.some((value) => typeof value === 'string' && value.toLowerCase().includes(needle));
};

