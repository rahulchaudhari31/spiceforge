const loadDB = (): MockDB => {
  if (typeof window !== 'undefined') {
    try {
      const raw = window.localStorage.getItem(STORAGE_KEY);
      if (raw) {
        const parsed = JSON.parse(raw) as MockDB;
        if (parsed && Array.isArray(parsed.customers)) {
          return parsed;
        }
      }
    } catch {
      // fall through to seed
    }
  }
  return createSeed();
};

